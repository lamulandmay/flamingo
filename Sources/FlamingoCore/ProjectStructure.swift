import Foundation

/// The one structure every Flamingo project has (plan 18). It is the same in every project:
/// only what is written inside the files differs. Every name and every fixed byte lives here,
/// and the scaffolder, the checker, the `## Structure` text agents read and CONTRACT all come
/// from it. A change ships as a new version with a migration, never as a variation.
///
/// ```
/// <project>/
/// ├── AGENTS.md        how to work here; every agent reads it
/// ├── CLAUDE.md        exactly "@AGENTS.md"
/// ├── README.md        what this is, for people
/// ├── HANDOVER.md      where the work stands
/// ├── .gitignore       Flamingo's block between fixed markers
/// ├── plans/           NN-slug.md, and .gitkeep
/// ├── docs/            everything else written about the project, and .gitkeep
/// └── scratch/         ignored by git; NOW.md and thoughts/ are written by Flamingo
/// ```
public enum ProjectStructure {
    public static let version = 1

    public static let agents = "AGENTS.md"
    public static let claude = "CLAUDE.md"
    public static let readme = "README.md"
    public static let handover = "HANDOVER.md"
    public static let gitignore = ".gitignore"
    public static let plans = "plans"
    public static let docs = "docs"
    public static let scratch = "scratch"
    public static let keep = ".gitkeep"
    /// Generated by Flamingo, not scaffolded: who is working here now.
    public static let now = "scratch/NOW.md"
    /// Generated by Flamingo, not scaffolded: a read-only copy of the thoughts on this project's files.
    public static let thoughts = "scratch/thoughts"

    /// Created in this order, so a folder always exists before what goes in it.
    public static let folders = [plans, docs, scratch]
    public static let keepFiles = [plans + "/" + keep, docs + "/" + keep]

    public static let claudeText = "@" + agents + "\n"
    public static let handoverText = "# Handover\n"

    public static let gitignoreBegin = "# flamingo structure 1: do not edit between these lines"
    public static let gitignoreEnd = "# flamingo end"
    public static let gitignoreLines = [scratch + "/", ".flamingo/", ".DS_Store"]
    public static var gitignoreBlock: String {
        ([gitignoreBegin] + gitignoreLines + [gitignoreEnd]).joined(separator: "\n") + "\n"
    }

    /// `AGENTS.md`'s second-level headings, in order. Their content is the project's own,
    /// except `Structure`, whose text is `structureText` everywhere.
    public static let headings = ["Rules", "Commands", "Memory", "Structure"]

    public static let structureText = """
    This project uses Flamingo's project structure, version 1. Every project that uses it has \
    the same files and folders; only what is written in them differs.

    - `AGENTS.md`: this file, read by every agent. `CLAUDE.md` only imports it.
    - `README.md`: what the project is, for people.
    - `HANDOVER.md`: where the work stands. Update it before you stop.
    - `plans/NN-slug.md`: one plan per piece of work, numbered in order (`01-auth.md`, `02-billing.md`).
    - `docs/`: everything else written about the project.
    - `scratch/`: ignored by git. Put throwaway output here: screenshots, logs, experiments.
    - `scratch/NOW.md`: written by Flamingo. Who is working here now and which files they are \
    changing. Read it first.
    - `scratch/thoughts/<path>.md`: the thoughts people left on `<path>`, and where in it. Read \
    them before you change that file. Read only.

    Create no other Markdown files at the root. Code and toolchain files go wherever the \
    toolchain wants them. Put what the next agent must know under Memory in this file, not \
    only in your own memory.

    """

    /// Markdown allowed at the root besides the four of the structure.
    public static let rootMarkdown: Set<String> = [
        agents, claude, readme, handover,
        "CHANGELOG.md", "CONTRIBUTING.md", "SECURITY.md", "CODE_OF_CONDUCT.md", "LICENSE.md",
    ]

    public static func isMarkdown(_ name: String) -> Bool {
        let ext = (name as NSString).pathExtension.lowercased()
        return ext == "md" || ext == "markdown"
    }

    /// `NN-slug.md`: two or more digits, then lowercase words joined by single hyphens.
    public static func isPlanName(_ name: String) -> Bool {
        name.range(of: #"^[0-9]{2,}-[a-z0-9]+(-[a-z0-9]+)*\.md$"#, options: .regularExpression) != nil
    }

    public static func agentsText(name: String, project: UUID, description: String = "") -> String {
        let about = description.trimmingCharacters(in: .whitespacesAndNewlines)
        var text = "# \(name)\n" + ProjectMarker(project: project).rendered + "\n"
        if !about.isEmpty { text += "\n\(about)\n" }
        for heading in headings.dropLast() { text += "\n## \(heading)\n" }
        return text + "\n## \(headings.last!)\n\n" + structureText
    }

    public static func readmeText(name: String) -> String { "# \(name)\n" }
}

/// The line in `AGENTS.md` that makes a folder a project: which project, which structure.
/// It lives in a tracked file, so every worktree, clone and moved copy carries the same id.
public struct ProjectMarker: Equatable, Sendable {
    public var project: UUID
    public var structure: Int

    public init(project: UUID, structure: Int = ProjectStructure.version) {
        self.project = project; self.structure = structure
    }

    private static let prefix = "<!-- flamingo: "
    private static let suffix = " -->"

    public var rendered: String {
        Self.prefix + "{\"project\":\"\(project.uuidString)\",\"structure\":\(structure)}" + Self.suffix
    }

    /// The first marker line in `text`, if one is readable.
    public static func find(in text: String) -> ProjectMarker? {
        for raw in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = raw.trimmingCharacters(in: .whitespaces)
            guard line.hasPrefix(prefix), line.hasSuffix(suffix) else { continue }
            let json = line.dropFirst(prefix.count).dropLast(suffix.count)
            guard let object = try? JSONSerialization.jsonObject(with: Data(json.utf8)) as? [String: Any],
                  let id = (object["project"] as? String).flatMap(UUID.init(uuidString:)),
                  let version = object["structure"] as? Int else { continue }
            return ProjectMarker(project: id, structure: version)
        }
        return nil
    }
}

/// One way a folder differs from the structure. Paths are relative to the project root.
public enum ProjectIssue: Equatable, Hashable, Sendable, CustomStringConvertible {
    case missingFolder(String)
    case missingFile(String)
    /// A fixed folder's name is taken by a file, or a fixed file's by a folder.
    case wrongKind(String)
    /// `CLAUDE.md` holds more than `@AGENTS.md`.
    case claudeChanged
    case gitignoreBlockMissing
    case gitignoreBlockChanged
    /// `AGENTS.md` exists but carries no marker: someone else's instructions, not yet merged.
    case markerMissing
    /// The marker names a structure this build doesn't know. Nothing is touched.
    case newerStructure(Int)
    case headingMissing(String)
    case headingsOutOfOrder
    case extraHeading(String)
    case structureTextChanged
    case strayRootMarkdown(String)
    case badPlanName(String)
    case folderInPlans(String)

    /// Fixed content with one right answer: Flamingo can put it back without asking.
    public var isRestorable: Bool {
        switch self {
        case .missingFolder, .missingFile, .claudeChanged, .gitignoreBlockMissing, .gitignoreBlockChanged,
             .headingMissing, .structureTextChanged: true
        default: false
        }
    }

    public var description: String {
        switch self {
        case .missingFolder(let p): "missing folder \(p)/"
        case .missingFile(let p): "missing \(p)"
        case .wrongKind(let p): "\(p) is the wrong kind of item"
        case .claudeChanged: "\(ProjectStructure.claude) holds more than @\(ProjectStructure.agents)"
        case .gitignoreBlockMissing: "\(ProjectStructure.gitignore) has no Flamingo block"
        case .gitignoreBlockChanged: "\(ProjectStructure.gitignore) Flamingo block was changed"
        case .markerMissing: "\(ProjectStructure.agents) has no Flamingo marker"
        case .newerStructure(let v): "structure version \(v) is newer than this build"
        case .headingMissing(let h): "\(ProjectStructure.agents) is missing ## \(h)"
        case .headingsOutOfOrder: "\(ProjectStructure.agents) headings are out of order"
        case .extraHeading(let h): "\(ProjectStructure.agents) has an extra ## \(h)"
        case .structureTextChanged: "\(ProjectStructure.agents) ## Structure text was changed"
        case .strayRootMarkdown(let p): "\(p) is Markdown at the root"
        case .badPlanName(let p): "\(p) is not named NN-slug.md"
        case .folderInPlans(let p): "\(p)/ is a folder inside plans"
        }
    }
}

public struct ProjectReport: Equatable, Sendable {
    public var marker: ProjectMarker?
    public var issues: [ProjectIssue]
    public var isStructured: Bool { marker != nil }
}

/// Compares a folder with the structure. Reads only; never writes.
public enum ProjectChecker {
    public static func check(root: URL) -> ProjectReport {
        let fm = FileManager.default
        let agentsText = read(root, ProjectStructure.agents)
        let marker = agentsText.flatMap(ProjectMarker.find(in:))
        if let marker, marker.structure > ProjectStructure.version {
            return ProjectReport(marker: marker, issues: [.newerStructure(marker.structure)])
        }
        var issues: [ProjectIssue] = []

        for folder in ProjectStructure.folders {
            switch kind(root, folder) {
            case nil: issues.append(.missingFolder(folder))
            case false: issues.append(.wrongKind(folder))
            case true: break
            }
        }
        let files = [ProjectStructure.agents, ProjectStructure.claude, ProjectStructure.readme, ProjectStructure.handover]
            + ProjectStructure.keepFiles
        for file in files {
            // A folder whose name is taken by a file was reported above; don't look inside it.
            let parent = (file as NSString).deletingLastPathComponent
            if !parent.isEmpty, kind(root, parent) == false { continue }
            switch kind(root, file) {
            case nil: issues.append(.missingFile(file))
            case true: issues.append(.wrongKind(file))
            case false: break
            }
        }

        if let claude = read(root, ProjectStructure.claude),
           claude.trimmingCharacters(in: .whitespacesAndNewlines) != ProjectStructure.claudeText.trimmingCharacters(in: .whitespacesAndNewlines) {
            issues.append(.claudeChanged)
        }
        if let block = gitignoreState(read(root, ProjectStructure.gitignore)) { issues.append(block) }

        if let agentsText {
            if marker == nil { issues.append(.markerMissing) }
            issues += agentsIssues(agentsText)
        }

        if let names = try? fm.contentsOfDirectory(atPath: root.path) {
            for name in names.sorted() where ProjectStructure.isMarkdown(name) && kind(root, name) == false
                && !ProjectStructure.rootMarkdown.contains(name) {
                issues.append(.strayRootMarkdown(name))
            }
        }
        if kind(root, ProjectStructure.plans) == true,
           let names = try? fm.contentsOfDirectory(atPath: root.appendingPathComponent(ProjectStructure.plans).path) {
            for name in names.sorted() where !name.hasPrefix(".") {
                let path = ProjectStructure.plans + "/" + name
                if kind(root, path) == true { issues.append(.folderInPlans(path)) }
                else if !ProjectStructure.isPlanName(name) { issues.append(.badPlanName(path)) }
            }
        }
        return ProjectReport(marker: marker, issues: issues)
    }

    /// `nil` when the block is exactly right.
    static func gitignoreState(_ text: String?) -> ProjectIssue? {
        guard let text else { return .gitignoreBlockMissing }
        let lines = text.components(separatedBy: "\n").map { $0.trimmingCharacters(in: .whitespaces) }
        guard let begin = lines.firstIndex(of: ProjectStructure.gitignoreBegin) else { return .gitignoreBlockMissing }
        guard let end = lines[begin...].firstIndex(of: ProjectStructure.gitignoreEnd),
              Array(lines[(begin + 1)..<end]) == ProjectStructure.gitignoreLines else { return .gitignoreBlockChanged }
        return nil
    }

    /// Second-level headings outside fenced code, in order.
    static func headings(in text: String) -> [String] {
        var out: [String] = []
        var fenced = false
        for line in text.components(separatedBy: "\n") {
            if line.hasPrefix("```") || line.hasPrefix("~~~") { fenced.toggle(); continue }
            if !fenced, line.hasPrefix("## ") { out.append(line.dropFirst(3).trimmingCharacters(in: .whitespaces)) }
        }
        return out
    }

    /// The lines under `## heading`, up to the next second-level heading.
    static func section(_ heading: String, in text: String) -> String? {
        var fenced = false
        var body: [String]?
        for line in text.components(separatedBy: "\n") {
            if line.hasPrefix("```") || line.hasPrefix("~~~") { fenced.toggle() }
            if !fenced, line.hasPrefix("## ") {
                if body != nil { break }
                if line.dropFirst(3).trimmingCharacters(in: .whitespaces) == heading { body = [] }
                continue
            }
            body?.append(line)
        }
        return body?.joined(separator: "\n")
    }

    static func agentsIssues(_ text: String) -> [ProjectIssue] {
        let found = headings(in: text)
        let fixed = ProjectStructure.headings
        var issues: [ProjectIssue] = fixed.filter { !found.contains($0) }.map { .headingMissing($0) }
        issues += found.filter { !fixed.contains($0) }.map { .extraHeading($0) }
        let order = found.filter { fixed.contains($0) }
        if issues.allSatisfy({ if case .headingMissing = $0 { false } else { true } }), order != fixed {
            issues.append(.headingsOutOfOrder)
        }
        if let body = section("Structure", in: text),
           body.trimmingCharacters(in: .whitespacesAndNewlines) != ProjectStructure.structureText.trimmingCharacters(in: .whitespacesAndNewlines) {
            issues.append(.structureTextChanged)
        }
        return issues
    }

    static func read(_ root: URL, _ path: String) -> String? {
        guard kind(root, path) == false else { return nil }
        return try? String(contentsOf: root.appendingPathComponent(path), encoding: .utf8)
    }

    /// `true` for a folder, `false` for anything else, `nil` when nothing is there.
    /// Doesn't follow a symlink at the end of the path.
    static func kind(_ root: URL, _ path: String) -> Bool? {
        guard let type = try? FileManager.default.attributesOfItem(atPath: root.appendingPathComponent(path).path)[.type]
                as? FileAttributeType else { return nil }
        return type == .typeDirectory
    }
}

/// One step of making a folder into a project.
public enum ProjectChange: Equatable, Sendable, CustomStringConvertible {
    case gitInit
    case createFolder(String)
    case createFile(String, String)
    /// Add the block to an existing `.gitignore`, leaving every other line as it is.
    case addGitignoreBlock

    public var description: String {
        switch self {
        case .gitInit: "git init"
        case .createFolder(let p): "+ \(p)/"
        case .createFile(let p, _): "+ \(p)"
        case .addGitignoreBlock: "~ \(ProjectStructure.gitignore)"
        }
    }
}

public struct ProjectPlan: Equatable, Sendable {
    public var root: URL
    public var marker: ProjectMarker
    public var changes: [ProjectChange]
    /// What only a conversion can settle: someone's CLAUDE.md, loose Markdown, odd plan names.
    /// `apply` refuses while any remain, so a folder is never left half structured.
    public var conflicts: [ProjectIssue]
}

public enum ProjectStructureError: Error, Equatable, LocalizedError {
    case notAFolder(String)
    case needsConversion([ProjectIssue])
    case newerStructure(Int)
    case gitFailed(String)
    /// Something Flamingo wrote or moved changed since, so it won't be taken back.
    case changed(String)

    public var errorDescription: String? {
        switch self {
        case .notAFolder(let p): "\(p) is not a folder."
        case .needsConversion(let issues): "Needs converting first: " + issues.map(\.description).joined(separator: "; ") + "."
        case .newerStructure(let v): "This project uses structure version \(v), newer than this build."
        case .gitFailed(let message): "git init failed: \(message)"
        case .changed(let p): "\(p) changed since Flamingo touched it. Nothing was undone."
        }
    }
}

/// Creates what the structure is missing. Never overwrites, never moves, never deletes.
public enum ProjectScaffolder {
    /// Runs `git init` in a folder. Tests pass their own.
    public typealias GitInit = (URL) throws -> Void

    public static func plan(root: URL, name: String? = nil, description: String = "", project: UUID = UUID()) -> ProjectPlan {
        let report = ProjectChecker.check(root: root)
        let marker = report.marker ?? ProjectMarker(project: project)
        var changes: [ProjectChange] = []
        var conflicts: [ProjectIssue] = []

        if ProjectChecker.kind(root, ".git") == nil { changes.append(.gitInit) }
        for issue in report.issues {
            switch issue {
            case .missingFolder(let folder): changes.append(.createFolder(folder))
            case .missingFile(let file): changes.append(.createFile(file, contents(of: file, marker: marker, name: name ?? root.lastPathComponent, description: description)))
            case .gitignoreBlockMissing:
                changes.append(ProjectChecker.kind(root, ProjectStructure.gitignore) == nil
                    ? .createFile(ProjectStructure.gitignore, ProjectStructure.gitignoreBlock) : .addGitignoreBlock)
            default: conflicts.append(issue)
            }
        }
        // Folders first, so the files that go in them have somewhere to land.
        let ordered = changes.filter { if case .gitInit = $0 { true } else { false } }
            + changes.filter { if case .createFolder = $0 { true } else { false } }
            + changes.filter { if case .createFile = $0 { true } else if case .addGitignoreBlock = $0 { true } else { false } }
        return ProjectPlan(root: root, marker: marker, changes: ordered, conflicts: conflicts)
    }

    static func contents(of file: String, marker: ProjectMarker, name: String, description: String) -> String {
        switch file {
        case ProjectStructure.agents: ProjectStructure.agentsText(name: name, project: marker.project, description: description)
        case ProjectStructure.claude: ProjectStructure.claudeText
        case ProjectStructure.readme: ProjectStructure.readmeText(name: name)
        case ProjectStructure.handover: ProjectStructure.handoverText
        default: ""
        }
    }

    /// Applies `plan` and returns the paths it created, in order. A file that appeared since
    /// the plan was made is left alone and not listed.
    @discardableResult
    public static func apply(_ plan: ProjectPlan, gitInit: GitInit = systemGitInit) throws -> [String] {
        var isDir: ObjCBool = false
        guard FileManager.default.fileExists(atPath: plan.root.path, isDirectory: &isDir), isDir.boolValue else {
            throw ProjectStructureError.notAFolder(plan.root.path)
        }
        if let newer = plan.conflicts.first(where: { if case .newerStructure = $0 { true } else { false } }),
           case .newerStructure(let v) = newer {
            throw ProjectStructureError.newerStructure(v)
        }
        guard plan.conflicts.isEmpty else { throw ProjectStructureError.needsConversion(plan.conflicts) }

        var created: [String] = []
        for change in plan.changes {
            switch change {
            case .gitInit:
                if ProjectChecker.kind(plan.root, ".git") == nil {
                    try gitInit(plan.root)
                    created.append(".git")
                }
            case .createFolder(let folder):
                let url = plan.root.appendingPathComponent(folder, isDirectory: true)
                if ProjectChecker.kind(plan.root, folder) == nil {
                    try FileManager.default.createDirectory(at: url, withIntermediateDirectories: false)
                    created.append(folder)
                }
            case .createFile(let file, let text):
                do {
                    try Data(text.utf8).write(to: plan.root.appendingPathComponent(file), options: .withoutOverwriting)
                    created.append(file)
                } catch CocoaError.fileWriteFileExists {
                    continue
                }
            case .addGitignoreBlock:
                let url = plan.root.appendingPathComponent(ProjectStructure.gitignore)
                let text = (try? String(contentsOf: url, encoding: .utf8)) ?? ""
                guard ProjectChecker.gitignoreState(text) == .gitignoreBlockMissing else { continue }
                let separator = text.isEmpty ? "" : text.hasSuffix("\n\n") ? "" : text.hasSuffix("\n") ? "\n" : "\n\n"
                try AtomicFile.write(Data((text + separator + ProjectStructure.gitignoreBlock).utf8), to: url)
            }
        }
        return created
    }

    public static func systemGitInit(_ root: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/git")
        process.arguments = ["init", "--quiet"]
        process.currentDirectoryURL = root
        let errors = Pipe()
        process.standardError = errors
        process.standardOutput = FileHandle.nullDevice
        do { try process.run() } catch { throw ProjectStructureError.gitFailed(error.localizedDescription) }
        process.waitUntilExit()
        guard process.terminationStatus == 0 else {
            let message = String(decoding: errors.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
            throw ProjectStructureError.gitFailed(message.trimmingCharacters(in: .whitespacesAndNewlines))
        }
    }
}
